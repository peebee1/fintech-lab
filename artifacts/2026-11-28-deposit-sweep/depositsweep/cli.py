"""Command line entry: `bench` writes results/, `show` prints without writing."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from .bench import run

RESULTS = Path(__file__).resolve().parents[1] / "results"


def dollars(cents: int) -> str:
    sign = "-" if cents < 0 else ""
    whole, part = divmod(abs(cents), 100)
    return f"{sign}${whole:,}.{part:02d}"


def pct(bps: int) -> str:
    return f"{bps / 100:.2f}%"


def render_markdown(data: dict) -> str:
    book = data["book"]
    lines = [
        "# Deposit sweep results",
        "",
        f"Generated by `python -m depositsweep.cli bench`, seed {data['seed']}.",
        "Synthetic book, integer cents, no network, no wall clock.",
        "",
        f"Book: {book['customers']} customers, {dollars(book['total_cents'])} of deposits, "
        f"mean {dollars(book['mean_cents'])}, median {dollars(book['median_cents'])}, "
        f"largest {dollars(book['max_cents'])}. "
        f"Top 5 percent of customers hold {pct(book['top5pct_share_bps'])} of the book.",
        f"Network capacity {dollars(book['capacity_cents'])}, "
        f"{pct(book['capacity_cover_bps'])} of the book.",
        f"Link fee {dollars(data['link_fee_cents'])} per customer per bank per year.",
        "",
        "## Policies",
        "",
        "| Policy | Max links | Interest | Blended APY | Link cost | Net | Links | "
        "Uninsured | Uninsured share | Exposed customers | Banks full |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for p in data["policies"]:
        lines.append(
            f"| {p['policy']} | {p['max_links']} | {dollars(p['interest_cents'])} | "
            f"{pct(p['blended_apy_bps'])} | {dollars(p['link_cost_cents'])} | "
            f"{dollars(p['net_cents'])} | {p['links']} | {dollars(p['uninsured_cents'])} | "
            f"{pct(p['uninsured_bps'])} | {p['exposed_customers']} | {p['banks_full']} |"
        )

    lines += [
        "",
        "## Link sweep",
        "",
        "| Max links per customer | Interest | Link cost | Net | Links | Uninsured | "
        "Uninsured share | Exposed customers |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in data["sweep"]:
        lines.append(
            f"| {row['max_links']} | {dollars(row['interest_cents'])} | "
            f"{dollars(row['link_cost_cents'])} | {dollars(row['net_cents'])} | "
            f"{row['links']} | {dollars(row['uninsured_cents'])} | "
            f"{pct(row['uninsured_bps'])} | {row['exposed_customers']} |"
        )

    conc = data["uninsured_concentration"]
    order = data["order_sensitivity"]
    small = data["small_book_test"]
    lines += [
        "",
        "## Concentration and order",
        "",
        f"Under the yield-only default, {conc['exposed_customers']} customers are exposed. "
        f"The ten largest uninsured balances hold {dollars(conc['top10_uninsured_cents'])}, "
        f"{pct(conc['top10_share_bps'])} of the uninsured dollars.",
        "",
        f"Allocation order changes interest by {dollars(order['interest_delta_cents'])} "
        f"(largest first minus smallest first) and changes uninsured dollars by "
        f"{dollars(order['uninsured_delta_cents'])}.",
        "",
        "## Where the invariance breaks",
        "",
        f"A book of {small['customers']} customers, {dollars(small['total_cents'])}, fits inside the "
        f"top bank, so capacity stops binding. There the cap costs "
        f"{dollars(small['yield_delta_cents'])}, {small['yield_delta_bps_x100'] / 100:.2f} bps of "
        f"yield: "
        f"{dollars(small['yield_only_interest_cents'])} at {small['yield_only_links']} links under "
        f"yield only, {dollars(small['capped_3_interest_cents'])} at {small['capped_3_links']} links "
        f"capped at three. Uninsured goes from "
        f"{dollars(small['yield_only_uninsured_cents'])} to "
        f"{dollars(small['capped_3_uninsured_cents'])}.",
        "",
        "## Checks",
        "",
        "| Check | Result | Detail |",
        "|---|---|---|",
    ]
    for c in data["checks"]:
        lines.append(f"| {c['name']} | {'pass' if c['ok'] else 'FAIL'} | {c['detail']} |")
    lines.append("")
    return "\n".join(lines)


def write_results(directory: Path | None = None, seed: int = 20261128) -> dict:
    target = RESULTS if directory is None else directory
    data = run(seed)
    target.mkdir(parents=True, exist_ok=True)
    (target / "summary.json").write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (target / "summary.md").write_text(render_markdown(data), encoding="utf-8")
    return data


def show(seed: int = 20261128) -> None:
    data = run(seed)
    print(render_markdown(data))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Deposit sweep bench")
    sub = parser.add_subparsers(dest="command", required=True)
    bench = sub.add_parser("bench", help="write results/")
    bench.add_argument("--seed", type=int, default=20261128)
    view = sub.add_parser("show", help="print without writing")
    view.add_argument("--seed", type=int, default=20261128)
    args = parser.parse_args(argv)

    if args.command == "bench":
        data = write_results(seed=args.seed)
        for p in data["policies"]:
            print(
                f"{p['policy']:<10} interest {dollars(p['interest_cents']):>14} "
                f"links {p['links']:>5} uninsured {dollars(p['uninsured_cents']):>13} "
                f"({pct(p['uninsured_bps'])}) exposed {p['exposed_customers']:>3}"
            )
        failed = [c for c in data["checks"] if not c["ok"]]
        print(f"checks: {len(data['checks']) - len(failed)} pass, {len(failed)} fail")
        return 0 if not failed else 1
    show(args.seed)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
